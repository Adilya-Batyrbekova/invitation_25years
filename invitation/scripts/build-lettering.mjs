// Offline font preparation. The parser never ships to the browser.
import { readFile, writeFile, copyFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";
import { format } from "prettier";
process.chdir(fileURLToPath(new URL("..", import.meta.url)));
const glyphs = {};
let units = 1000,
  ascent = 1000,
  descent = -300;
for (const subset of ["latin", "cyrillic"]) {
  const bytes = await readFile(
    `node_modules/@fontsource/great-vibes/files/great-vibes-${subset}-400-normal.woff`,
  );
  const font = opentype.parse(
    bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength),
  );
  units = font.unitsPerEm;
  ascent = font.ascender;
  descent = font.descender;
  const codes = [
    ...Array.from({ length: 95 }, (_, i) => 32 + i),
    ...Array.from({ length: 64 }, (_, i) => 0x410 + i),
    0x401,
    0x451,
    0xa0,
    0xab,
    0xbb,
    0x2013,
    0x2014,
    0x2018,
    0x2019,
    0x201c,
    0x201d,
    0x2026,
  ];
  for (const code of codes) {
    const char = String.fromCodePoint(code);
    const glyph = font.charToGlyph(char);
    if (!glyph.index) continue;
    glyphs[char] = {
      width: glyph.advanceWidth,
      path: glyph.getPath(0, 0, units).toPathData(1),
    };
  }
}
await writeFile(
  "src/data/lettering.ts",
  await format(
    `// Generated by scripts/build-lettering.mjs from Great Vibes (OFL-1.1).\nexport const lettering: {units:number;ascent:number;descent:number;glyphs:Record<string,{width:number;path:string}>} = ${JSON.stringify({ units, ascent, descent, glyphs })};\n`,
    { parser: "typescript" },
  ),
);
await copyFile(
  "node_modules/@fontsource/great-vibes/LICENSE",
  "public/art/Great-Vibes-OFL.txt",
);
console.log(
  `Prepared ${Object.keys(glyphs).length} glyphs; em=${units}, ascent=${ascent}, descent=${descent}`,
);
